    fecha_modificacion    TIMESTAMPTZ,
    ip_modificacion       VARCHAR(45),
    estado_registro       CHAR(1)      NOT NULL DEFAULT 'A' CHECK (estado_registro IN ('A','I'))
);

CREATE TABLE contenido_genero (
    id_contenido          BIGINT       NOT NULL REFERENCES contenido (id_contenido),
    id_genero             BIGINT       NOT NULL REFERENCES genero (id_genero),
    es_principal          BOOLEAN      NOT NULL DEFAULT FALSE,
    usuario_creacion      VARCHAR(100) NOT NULL DEFAULT 'SISTEMA',
    fecha_creacion        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ip_creacion           VARCHAR(45),
    usuario_modificacion  VARCHAR(100),
    fecha_modificacion    TIMESTAMPTZ,
    ip_modificacion       VARCHAR(45),
    estado_registro       CHAR(1)      NOT NULL DEFAULT 'A' CHECK (estado_registro IN ('A','I')),
    PRIMARY KEY (id_contenido, id_genero)
);
-- Un contenido tiene como máximo un género principal
CREATE UNIQUE INDEX uq_contenido_genero_principal
    ON contenido_genero (id_contenido) WHERE es_principal AND estado_registro = 'A';

