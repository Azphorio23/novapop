-- =====================================================================
--  NovaPop — Plataforma de streaming de películas y series
--  Script 01: Esquema de base de datos (PostgreSQL 15+ / Supabase)
--  35 tablas en 3FN · 7 campos de auditoría por tabla
-- =====================================================================
--  Campos de auditoría (presentes en TODAS las tablas):
--    usuario_creacion      quién creó el registro
--    fecha_creacion        cuándo se creó
--    ip_creacion           desde qué IP se creó
--    usuario_modificacion  quién lo modificó por última vez
--    fecha_modificacion    cuándo se modificó por última vez (lo pone un trigger)
--    ip_modificacion       desde qué IP se modificó
--    estado_registro       'A' = activo, 'I' = inactivo (borrado lógico)
--
--  Se usa el esquema "novapop" (y no "public") para que las tablas NO queden
--  expuestas por la Data API de Supabase; el backend se conecta por JDBC.
-- =====================================================================

DROP SCHEMA IF EXISTS novapop CASCADE;
CREATE SCHEMA novapop;
SET search_path TO novapop;

-- =====================================================================
--  SEGURIDAD (staff de la plataforma)
-- =====================================================================
CREATE TABLE rol (
    id_rol                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol            VARCHAR(50)  NOT NULL,
    descripcion           VARCHAR(255),
    usuario_creacion      VARCHAR(100) NOT NULL DEFAULT 'SISTEMA',
    fecha_creacion        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ip_creacion           VARCHAR(45),
    usuario_modificacion  VARCHAR(100),
    fecha_modificacion    TIMESTAMPTZ,
    ip_modificacion       VARCHAR(45),
    estado_registro       CHAR(1)      NOT NULL DEFAULT 'A' CHECK (estado_registro IN ('A','I')),
    CONSTRAINT uq_rol_nombre UNIQUE (nombre_rol)
);

CREATE TABLE usuario (
    id_usuario            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol                BIGINT       NOT NULL REFERENCES rol (id_rol),
    nombre_usuario        VARCHAR(50)  NOT NULL,
    nombres               VARCHAR(150) NOT NULL,
    correo                VARCHAR(150) NOT NULL,
    bloqueado             BOOLEAN      NOT NULL DEFAULT FALSE,
    clave_hash            VARCHAR(100), -- contraseña del panel de administración (BCrypt)
    usuario_creacion      VARCHAR(100) NOT NULL DEFAULT 'SISTEMA',
    fecha_creacion        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ip_creacion           VARCHAR(45),
    usuario_modificacion  VARCHAR(100),
    fecha_modificacion    TIMESTAMPTZ,
    ip_modificacion       VARCHAR(45),
    estado_registro       CHAR(1)      NOT NULL DEFAULT 'A' CHECK (estado_registro IN ('A','I')),
    CONSTRAINT uq_usuario_nombre UNIQUE (nombre_usuario),
    CONSTRAINT uq_usuario_correo UNIQUE (correo)
);

