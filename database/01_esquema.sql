-- 1) Auditoría: en cada UPDATE se sella fecha_modificacion y se impide
--    alterar los campos de creación.
CREATE OR REPLACE FUNCTION fn_auditoria_modificacion() RETURNS TRIGGER AS $$
BEGIN
    NEW.fecha_modificacion := CURRENT_TIMESTAMP;
    NEW.usuario_creacion   := OLD.usuario_creacion;
    NEW.fecha_creacion     := OLD.fecha_creacion;
    NEW.ip_creacion        := OLD.ip_creacion;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
DECLARE t RECORD;
BEGIN
    FOR t IN SELECT table_name FROM information_schema.tables
             WHERE table_schema = 'novapop' AND table_type = 'BASE TABLE'
    LOOP
        EXECUTE format(
            'CREATE TRIGGER tg_%1$s_auditoria BEFORE UPDATE ON novapop.%1$I
             FOR EACH ROW EXECUTE FUNCTION novapop.fn_auditoria_modificacion()', t.table_name);
    END LOOP;
END $$;

-- 2) Subtipos: PELICULA solo para contenidos tipo 'PELICULA' y
--    TEMPORADA solo para contenidos tipo 'SERIE'.
CREATE OR REPLACE FUNCTION fn_validar_subtipo_contenido() RETURNS TRIGGER AS $$
DECLARE v_tipo VARCHAR(10);
        v_esperado VARCHAR(10) := TG_ARGV[0];
BEGIN
    SELECT tipo_contenido INTO v_tipo FROM novapop.contenido WHERE id_contenido = NEW.id_contenido;
    IF v_tipo IS DISTINCT FROM v_esperado THEN
        RAISE EXCEPTION 'El contenido % es de tipo %, se esperaba %', NEW.id_contenido, v_tipo, v_esperado;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_pelicula_subtipo BEFORE INSERT OR UPDATE OF id_contenido ON pelicula
    FOR EACH ROW EXECUTE FUNCTION fn_validar_subtipo_contenido('PELICULA');
CREATE TRIGGER tg_temporada_subtipo BEFORE INSERT OR UPDATE OF id_contenido ON temporada
    FOR EACH ROW EXECUTE FUNCTION fn_validar_subtipo_contenido('SERIE');

-- 3) Coherencia contenido/episodio en SESION_REPRODUCCION e HISTORIAL_REPRODUCCION:
--    si hay episodio, debe pertenecer a la serie indicada en id_contenido;
--    si el contenido es una serie, el episodio es obligatorio.
CREATE OR REPLACE FUNCTION fn_validar_episodio_contenido() RETURNS TRIGGER AS $$
DECLARE v_tipo VARCHAR(10);
        v_contenido_episodio BIGINT;
BEGIN
    SELECT tipo_contenido INTO v_tipo FROM novapop.contenido WHERE id_contenido = NEW.id_contenido;
    IF NEW.id_episodio IS NULL THEN
        IF v_tipo = 'SERIE' THEN
            RAISE EXCEPTION 'El contenido % es una serie: se requiere id_episodio', NEW.id_contenido;
        END IF;
    ELSE
        SELECT t.id_contenido INTO v_contenido_episodio
          FROM novapop.episodio e JOIN novapop.temporada t ON t.id_temporada = e.id_temporada
         WHERE e.id_episodio = NEW.id_episodio;
        IF v_contenido_episodio IS DISTINCT FROM NEW.id_contenido THEN
            RAISE EXCEPTION 'El episodio % no pertenece al contenido %', NEW.id_episodio, NEW.id_contenido;
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_sesion_episodio BEFORE INSERT OR UPDATE OF id_contenido, id_episodio ON sesion_reproduccion
    FOR EACH ROW EXECUTE FUNCTION fn_validar_episodio_contenido();
CREATE TRIGGER tg_historial_episodio BEFORE INSERT OR UPDATE OF id_contenido, id_episodio ON historial_reproduccion
    FOR EACH ROW EXECUTE FUNCTION fn_validar_episodio_contenido();

